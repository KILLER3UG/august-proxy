"""End-to-end smoke: does the app START, and do its basic doors answer?

The test suite was deleted on 2026-10-17 at the owner's request. What
replaced it is a set of static gates — `npm run check:docs`, `check:sse`,
`check:brain-config`, `check:truncate` and friends — and they cover what
they can see: a frame nobody handles, a key nobody can write, a `truncate`
that cannot truncate.

What no static gate can see is the app **starting**. A module that fails to
import, a migration that does not apply, a lifespan hook that raises, a
router that fails to register — every one of those is invisible to a linter
and fatal at launch. This script is the floor under that: it imports the
real app, runs its lifespan, and asks a handful of read-only doors a
question.

It is deliberately NOT a behaviour test. It does not check that the app
computes the right thing; it checks that the app comes up and that the doors
the desktop shell opens on launch answer. The difference matters: a failure
here means "the app is broken", not "a rule changed".

**Scope.** This is BACKEND-only. It does not start the Tauri shell, so
"the app starts" means "the backend starts" — the shell's own bootstrap
(window creation, the backend supervisor, the install stamp) is not covered
here. Do not read a green run as "the desktop app launched".

**It never touches the user's data.** `AUGUST_DATA_DIR` is pointed at a
throwaway temp directory unless the caller says otherwise, and the temp
directory is removed afterwards. The app's own data directory holds
everything a user owns — brain database, provider keys, learned skills,
sessions — and a smoke check has no business being the thing that corrupts
it. `--data-dir` exists for the rare case of pointing it at a real
directory on purpose.

It also does not COPY the user's credentials out of the environment. The
app's lifespan mirrors the Google OAuth keys from the process environment
into `mcpGlobalEnv` — whose SENSITIVE half now goes into the encrypted
secret store and whose public half is persisted into `config.json` — so
without this, a smoke run would write this machine's OAuth secret into the
scratch directory. The inherited keys are removed before the app is
imported, so the mirror has nothing to copy in the first place.

Usage:
    python scripts/e2e_smoke.py             # scratch data, throwaway
    python scripts/e2e_smoke.py --data-dir X # use X (never the default)
"""

from __future__ import annotations

import argparse
import atexit
import json
import os
import shutil
import sys
import tempfile
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / 'backend-py'))

#: The token the smoke configures, so the sensitive local routes have a
#: credential to check. The real one is generated by the desktop shell and
#: never touches disk; this is a stand-in so the gate can prove the gate
#: works.
SMOKE_LOCAL_TOKEN = 'smoke-local-token-not-a-secret'

#: Environment keys the app MIRRORS into the persisted config. They are
#: removed before the app is imported so a smoke run cannot copy this
#: machine's OAuth secret into the scratch directory.
_INHERITED_SECRET_ENV = (
    'GOOGLE_OAUTH_CLIENT_ID',
    'GOOGLE_OAUTH_CLIENT_SECRET',
    'GOOGLE_OAUTH_REDIRECT_URI',
    'OAUTHLIB_INSECURE_TRANSPORT',
)


def _quiet_logs() -> None:
    """Keep the app's startup logging out of the report.

    The app logs a line per migration and a line per background service at
    startup — useful when a migration breaks, noise otherwise. The report is
    the thing being read.
    """
    import logging

    for name in list(logging.root.manager.loggerDict):
        logging.getLogger(name).setLevel(logging.WARNING)
    logging.getLogger().setLevel(logging.WARNING)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        '--data-dir',
        default=None,
        help='use this data directory instead of a throwaway one. NEVER pass the '
        'real one by accident — it holds the user\'s brain database and keys.',
    )
    parser.add_argument(
        '--json',
        action='store_true',
        help='print the report as JSON (for a CI step to read)',
    )
    args = parser.parse_args()

    if args.data_dir:
        data_dir = Path(args.data_dir).resolve()
        data_dir.mkdir(parents=True, exist_ok=True)
        scratch = False
    else:
        data_dir = Path(tempfile.mkdtemp(prefix='august-smoke-'))
        scratch = True
        atexit.register(lambda: shutil.rmtree(data_dir, ignore_errors=True))

    os.environ['AUGUST_DATA_DIR'] = str(data_dir)
    # The sensitive local routes need a credential to check. Configure one so
    # the gate can prove the gate works, and so a route that spawns workers
    # can never actually spawn one during a smoke run.
    os.environ['AUGUST_LOCAL_API_TOKEN'] = SMOKE_LOCAL_TOKEN
    for key in _INHERITED_SECRET_ENV:
        os.environ.pop(key, None)

    from app.main import app
    from fastapi.testclient import TestClient

    # AFTER the import: the app configures its own logging when it is
    # imported, so quieting the loggers before that is undone by the import.
    _quiet_logs()

    results: list[dict] = []
    section = ''

    def check(name: str, ok: bool, detail: str = '') -> None:
        results.append({'section': section, 'name': name, 'ok': ok, 'detail': detail})

    def begin(title: str) -> None:
        """Open a section. The report is grouped, because a flat list of
        checks is a list, and a list does not say whether the app came up
        or only its side doors answered."""
        nonlocal section
        section = title

    with TestClient(app) as client:
        # ── Section 1 · Startup ─────────────────────────────────────────
        # The app is up, and it says so. If this fails, nothing below it
        # means anything.
        begin('startup')
        try:
            response = client.get('/api/health')
            ok = response.status_code == 200
            check(
                'GET /api/health',
                ok,
                '' if ok else f'status {response.status_code}: {response.text[:200]}',
            )
        except Exception as exc:  # noqa: BLE001 — a failure IS the result
            check('GET /api/health', False, f'{type(exc).__name__}: {exc}')

        # ── Section 2 · Configuration ───────────────────────────────────
        # The two doors the Settings panel reads, and the one it writes.
        # The write matters: the brain-config panel's own keys must be
        # WRITABLE. This is the class of bug the static gate catches,
        # checked here too because it is cheap and it exercises the live
        # route rather than the validator in isolation.
        begin('configuration')
        for path in ('/api/config/safe', '/api/brain/config'):
            # Same Windows flake as the write below: a scanner or indexer can
            # hold the freshly created config.json for a moment. A retry that
            # RECOVERS is reported as recovered, so the flake stays visible.
            read_attempts = 0
            read_detail = ''
            read_ok = False
            for attempt in range(3):
                read_attempts += 1
                try:
                    response = client.get(path)
                    read_ok = response.status_code == 200
                    read_detail = (
                        '' if read_ok else f'status {response.status_code}'
                    )
                    if read_ok:
                        break
                except Exception as exc:  # noqa: BLE001
                    read_detail = f'{type(exc).__name__}: {exc}'
                    time.sleep(0.5 * (attempt + 1))
            check(
                f'GET {path}',
                read_ok,
                read_detail
                + ('' if read_attempts == 1 else f' (took {read_attempts} attempts)'),
            )

        # The write is retried: on Windows a virus scanner or a file indexer
        # can hold the freshly created config.json for a moment, and a
        # transient PermissionError there is not a product defect. A retry
        # that RECOVERS is reported as recovered — the flake is visible in
        # the output rather than silently smoothed over.
        write_attempts = 0
        write_detail = ''
        write_ok = False
        for attempt in range(3):
            write_attempts += 1
            try:
                response = client.put(
                    '/api/brain/config',
                    json={'maxWorkbenchToolLoops': 0},
                )
                write_ok = response.status_code == 200
                write_detail = (
                    ''
                    if write_ok
                    else f'status {response.status_code}: {response.text[:200]}'
                )
                if write_ok:
                    break
            except Exception as exc:  # noqa: BLE001
                write_detail = f'{type(exc).__name__}: {exc}'
                time.sleep(0.5 * (attempt + 1))
        check(
            'PUT /api/brain/config (maxWorkbenchToolLoops=0)',
            write_ok,
            write_detail
            + ('' if write_attempts == 1 else f' (took {write_attempts} attempts)'),
        )

        # ── Section 3 · Memory and skills ───────────────────────────────
        # The surfaces that read the brain database. If the brain will not
        # open, these are the doors that say so.
        begin('memory and skills')
        for path in (
            '/api/brain/memory/metrics',
            '/api/brain/skills/suggestions',
            '/api/agents',
        ):
            try:
                response = client.get(path)
                ok = response.status_code == 200
                check(
                    f'GET {path}',
                    ok,
                    '' if ok else f'status {response.status_code}',
                )
            except Exception as exc:  # noqa: BLE001
                check(f'GET {path}', False, f'{type(exc).__name__}: {exc}')

        # ── Section 4 · The harness door ────────────────────────────────
        # /mcp/harness must be CLOSED while external access is off. The
        # route dispatches real model calls and real tool execution, and
        # the browser origin guard does not cover a local script.
        begin('the harness door')
        try:
            response = client.post('/mcp/harness', json={'method': 'tools/list'})
            ok = response.status_code == 403
            check(
                'POST /mcp/harness is closed (403)',
                ok,
                '' if ok else f'status {response.status_code}',
            )
        except Exception as exc:  # noqa: BLE001
            check('POST /mcp/harness', False, f'{type(exc).__name__}: {exc}')

        # ── Section 5 · The local door ──────────────────────────────────
        # The routes that START work are behind a per-install token, because
        # "127.0.0.1" is "any process on this machine" and a model with
        # run_command can reach loopback. Without the token the route must
        # be refused; with it, the request must get past the door and fail
        # on its own terms (no such task) rather than on the credential.
        #
        # The task id is deliberately bogus: the point is to see 401 vs 404,
        # and a real task id would make this a behaviour test.
        begin('the local door')
        try:
            response = client.post(
                '/api/subagents/no-such-task/steer',
                json={'message': 'smoke'},
            )
            ok = response.status_code == 401
            check(
                'POST /api/subagents/{taskId}/steer without the token is refused (401)',
                ok,
                '' if ok else f'status {response.status_code}',
            )
        except Exception as exc:  # noqa: BLE001
            check('POST /api/subagents steer (no token)', False, f'{type(exc).__name__}: {exc}')

        try:
            response = client.post(
                '/api/subagents/no-such-task/steer',
                json={'message': 'smoke'},
                headers={'X-August-Local-Token': SMOKE_LOCAL_TOKEN},
            )
            # 404 = the credential was accepted and the task does not exist.
            # Anything 401-ish means the credential was rejected.
            ok = response.status_code == 404
            check(
                'POST /api/subagents/{taskId}/steer with the token passes the door (404)',
                ok,
                '' if ok else f'status {response.status_code}',
            )
        except Exception as exc:  # noqa: BLE001
            check('POST /api/subagents steer (with token)', False, f'{type(exc).__name__}: {exc}')

        # ── Section 6 · Policy and secret boundaries ──────────────────
        # These are static checks, but they belong with "does the app hold
        # together" rather than in a linter: a tool that writes a file but
        # is not classified as mutating runs without approval in plan/ask
        # mode, and a secret in a child environment is readable by any local
        # caller. Both classes were live defects.
        begin('policy and secret boundaries')
        try:
            from app.services import tool_policy

            unguarded = [
                name
                for name in tool_policy.FILE_WRITING_TOOLS
                if not tool_policy.is_mutating(name)
            ]
            check(
                'every file/config-writing tool is plan/ask mutating',
                not unguarded,
                ', '.join(sorted(unguarded)),
            )
        except Exception as exc:  # noqa: BLE001
            check('tool policy probe', False, f'{type(exc).__name__}: {exc}')

        # A deny set is a security table, and a name in it that no registry
        # registers can never fire. Check it against the POPULATED registry —
        # the app has already registered every group by the time this runs — so
        # a renamed spawn tool fails here instead of living as a dead row.
        # An empty registry is a failed probe, not a clean table.
        try:
            from app.services.tool_registry import listTools
            from app.services.workbench.subagent import _SPAWN_TOOLS, _SUBAGENT_NEVER_TOOLS

            registered = {
                str((t.get('function') or {}).get('name') or '')
                for t in listTools(include_host_agent=True)
            }
            unknown = sorted((_SUBAGENT_NEVER_TOOLS | _SPAWN_TOOLS) - registered)
            check(
                'every sub-agent deny name is a registered tool',
                bool(registered) and not unknown,
                ', '.join(unknown) if unknown else f'{len(registered)} registered tools checked',
            )
        except Exception as exc:  # noqa: BLE001
            check('sub-agent deny-set probe', False, f'{type(exc).__name__}: {exc}')

        try:
            from app.lib.async_subprocess import terminal_env

            env = terminal_env()
            leaked = [
                key
                for key in env
                if key.upper().startswith('AUGUST_')
                or 'TOKEN' in key.upper()
                or 'SECRET' in key.upper()
                or 'API_KEY' in key.upper()
            ]
            check(
                'terminal env carries no app credential',
                not leaked,
                ', '.join(sorted(leaked)),
            )
        except Exception as exc:  # noqa: BLE001
            check('terminal env probe', False, f'{type(exc).__name__}: {exc}')

        try:
            from app.lib.local_api_auth import LOCAL_AUTH_ENV

            check(
                'the local token is not left in os.environ for children',
                LOCAL_AUTH_ENV not in os.environ,
                '' if LOCAL_AUTH_ENV not in os.environ else LOCAL_AUTH_ENV,
            )
        except Exception as exc:  # noqa: BLE001
            check('local token env probe', False, f'{type(exc).__name__}: {exc}')

        # The workbench chat is the app's own start-work door; the terminal
        # REST list is the route that led to the token leak. Both must be
        # behind the same per-install credential as the subagent steer route.
        try:
            response = client.post('/api/workbench/chat', json={'message': 'smoke'})
            ok = response.status_code == 401
            check(
                'POST /api/workbench/chat without the token is refused (401)',
                ok,
                '' if ok else f'status {response.status_code}',
            )
        except Exception as exc:  # noqa: BLE001
            check('POST /api/workbench/chat (no token)', False, f'{type(exc).__name__}: {exc}')

        try:
            response = client.get('/api/terminal/sessions')
            ok = response.status_code == 401
            check(
                'GET /api/terminal/sessions without the token is refused (401)',
                ok,
                '' if ok else f'status {response.status_code}',
            )
        except Exception as exc:  # noqa: BLE001
            check('GET /api/terminal/sessions (no token)', False, f'{type(exc).__name__}: {exc}')

    failures = [r for r in results if not r['ok']]
    report = {
        'ok': not failures,
        'dataDir': str(data_dir),
        'scratch': scratch,
        'checks': len(results),
        'failures': failures,
    }

    if args.json:
        print(json.dumps(report, indent=2))
    else:
        current = None
        for r in results:
            if r['section'] != current:
                current = r['section']
                print(f'\n{current}')
            mark = 'ok  ' if r['ok'] else 'FAIL'
            detail = f'  ({r["detail"]})' if r['detail'] else ''
            print(f'  {mark} {r["name"]}{detail}')
        print(
            f'\n{len(results) - len(failures)}/{len(results)} smoke check(s) passed '
            f'({"scratch data" if scratch else "EXPLICIT data dir"}).'
        )

    return 1 if failures else 0


if __name__ == '__main__':
    raise SystemExit(main())
