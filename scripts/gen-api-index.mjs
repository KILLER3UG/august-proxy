#!/usr/bin/env node
/* ── gen-api-index.mjs — the COMPLETE route index ────────────────────────────
 *
 * `docs/API_REFERENCE.md` is hand-written: it explains the families a human
 * needs and carries 204 of the 412 routes. That is the right shape for prose
 * and the wrong shape for completeness — an audit found 323 routes whose
 * (METHOD path) pair appears nowhere in it, including every bots/rooms route,
 * the whole recurring-task family, and most of the subagent surface.
 *
 * So the two jobs are split:
 *
 *   API_REFERENCE.md   curated explanation of the families that matter.
 *                      Never generated — a generator cannot write the "why".
 *   API_INDEX.md       every route, grouped, with method, path, and the spec's
 *                      own summary. GENERATED, and drift-gated.
 *
 * Both are driven by `docs/api/openapi.json`, which `check-api.mjs` already
 * proves matches what the app actually serves — so this file cannot drift
 * further than the spec does, and the spec is checked on every CI run.
 *
 *   node scripts/gen-api-index.mjs            # write (or report up to date)
 *   node scripts/gen-api-index.mjs --check    # exit 1 on drift
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(SCRIPT_DIR, '..');
const SPEC = resolve(REPO, 'docs', 'api', 'openapi.json');
const OUT = resolve(REPO, 'docs', 'API_INDEX.md');
const CHECK = process.argv.includes('--check');

const BANNER = `<!-- GENERATED by scripts/gen-api-index.mjs from docs/api/openapi.json. -->
<!-- Do not edit by hand: \`npm run check:api-index\` fails when it drifts.   -->
<!-- The spec itself is drift-gated by scripts/check-api.mjs.                  -->
<!-- For family-by-family prose, see docs/API_REFERENCE.md.                   -->`;

/**
 * Group routes by the area a reader looks for them under. Order here is the
 * order in the output; anything unmatched lands in "Other", which is itself a
 * useful signal that a family needs naming.
 */
const GROUPS = [
  { id: 'v1', title: 'AI proxy (`/v1/*`)', match: (p) => p.startsWith('/v1') },
  { id: 'workbench', title: 'Workbench chat', prefix: '/api/workbench' },
  { id: 'sessions', title: 'Sessions & transcripts', prefix: '/api/sessions' },
  { id: 'brain', title: 'Memory & brain', prefix: '/api/brain' },
  { id: 'skills', title: 'Skills', match: (p) => p.startsWith('/api/skills') },
  { id: 'curator', title: 'Curator & learning', match: (p) => p.startsWith('/api/curator') },
  { id: 'harness', title: 'Harness', match: (p) => p.startsWith('/api/harness') },
  { id: 'subagents', title: 'Subagents & agents', match: (p) => /^\/api\/(subagents|agents)/.test(p) },
  { id: 'providers', title: 'Providers & models', match: (p) => /^\/api\/(providers|models|family)/.test(p) },
  { id: 'config', title: 'Configuration', match: (p) => /^\/api\/(config|features)/.test(p) },
  { id: 'mcp', title: 'MCP & integrations', match: (p) => /^\/api\/(mcp|service-connections)/.test(p) },
  { id: 'tools', title: 'Tools, files & git', match: (p) => /^\/api\/(git|terminal|files|fs)/.test(p) },
  { id: 'automations', title: 'Automations & tasks', match: (p) => /^\/api\/(automations|tasks|calendar|recurring)/.test(p) },
  { id: 'kanban', title: 'Kanban & workstreams', match: (p) => /^\/api\/(kanban|workstreams)/.test(p) },
  { id: 'live', title: 'Live / voice', match: (p) => /^\/api\/(live|voice)/.test(p) },
  { id: 'gateway', title: 'Gateway & access', match: (p) => /^\/api\/(gateway|access|external)/.test(p) },
  { id: 'manage', title: 'August manage & security', match: (p) => /^\/api\/(august|manage|security|audit|privacy|rollback)/.test(p) },
  { id: 'observability', title: 'Observability & logs', match: (p) => /^\/api\/(health|logs|monitor|observ|perf|usage|review|preview|circuit)/.test(p) },
  { id: 'desktop', title: 'Desktop automation', match: (p) => /^\/api\/(desktop|browser|observation)/.test(p) },
];

const METHOD_ORDER = ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'WS'];

/** Escape a cell for a markdown table and collapse newlines. */
function cell(text, max = 0) {
  let out = String(text ?? '')
    .replace(/\r?\n+/g, ' ')
    .replace(/\|/g, '\\|')
    .trim();
  if (max && out.length > max) out = `${out.slice(0, max - 1)}…`;
  return out;
}

function groupFor(path) {
  for (const g of GROUPS) {
    if (g.prefix && path.startsWith(g.prefix)) return g;
    if (g.match && g.match(path)) return g;
  }
  return { id: 'other', title: 'Other' };
}

/**
 * Choose what to print in the Summary column.
 *
 * Order matters. FastAPI fills `summary` from the handler name with underscores
 * stripped ("Listmodels") whenever a route does not declare one, so `summary`
 * alone is often a mangled identifier. The ROUTE DOCSTRING lands in
 * `description` and is usually a real sentence, so it is preferred. Only when
 * neither is prose do we fall back to the parameter/body shape, which is what a
 * caller actually needs to build a request.
 */
function describe(op, path) {
  const summary = String(op?.summary || '').trim();
  const description = String(op?.description || '').trim();

  // A docstring's first paragraph is the sentence worth showing.
  const lead = description.split(/\n\s*\n/)[0]?.replace(/\s+/g, ' ').trim() || '';
  if (lead && /\s/.test(lead)) return lead;

  if (summary && /\s/.test(summary)) return summary;

  const bits = [];
  const pathParams = [...(path.matchAll(/\{([^}]+)\}/g) || [])].map((m) => m[1]);
  if (pathParams.length) bits.push(`path: ${pathParams.join(', ')}`);

  const query = Object.entries(op?.parameters ?? {})
    .filter(([, v]) => v?.in === 'query')
    .map(([k]) => k);
  if (query.length) bits.push(`query: ${query.join(', ')}`);

  if (op?.requestBody?.content) bits.push('body: JSON');

  if (bits.length) return bits.join(' · ');
  return summary || '';
}

function build() {
  if (!existsSync(SPEC)) {
    console.error(`[gen-api-index] missing ${SPEC} — run: npm run gen:api`);
    process.exit(2);
  }
  const spec = JSON.parse(readFileSync(SPEC, 'utf-8'));

  const rows = [];
  for (const [path, ops] of Object.entries(spec.paths ?? {})) {
    for (const [method, op] of Object.entries(ops)) {
      if (!METHOD_ORDER.includes(method.toUpperCase())) continue;
      const summary = op?.summary || op?.description || '';
      const params = [
        ...Object.keys(op?.parameters ?? {}),
        ...Object.keys(op?.requestBody?.content ?? {}).length ? ['body'] : [],
      ];
      rows.push({
        method: method.toUpperCase(),
        path,
        // FastAPI derives a default summary from the handler's function name
        // with underscores stripped ("list_models" → "Listmodels"). Those carry
        // no information the path does not already give, and the spec does not
        // retain the original name to split them back apart — so when the
        // summary is just the path's own tail, show the parameter shape
        // instead, which is what a reader actually needs.
        summary: cell(describe(op, path), 110),
        params: params.length ? cell(params.join(', '), 70) : '',
        deprecated: op?.deprecated ? 'yes' : '',
      });
    }
  }

  rows.sort(
    (a, b) =>
      a.path.localeCompare(b.path) ||
      METHOD_ORDER.indexOf(a.method) - METHOD_ORDER.indexOf(b.method),
  );

  const byGroup = new Map(GROUPS.map((g) => [g.id, []]));
  const other = [];
  for (const r of rows) {
    const g = groupFor(r.path);
    (g.id === 'other' ? other : byGroup.get(g.id)).push(r);
  }

  const lines = [
    BANNER,
    '',
    '# API Index — every route',
    '',
    `${rows.length} routes across ${spec.paths ? Object.keys(spec.paths).length : 0} paths,`,
    'grouped by family. **This file is generated.** For the prose that explains what',
    'these are for and when to reach for them, read',
    '[`API_REFERENCE.md`](./API_REFERENCE.md) — it covers the families that matter in',
    'depth but is hand-written, so it is deliberately not exhaustive.',
    '',
    'Regenerate: `npm run gen:api-index` · Verify: `npm run check:api-index`',
    '',
  ];

  for (const g of GROUPS) {
    const list = byGroup.get(g.id) || [];
    if (!list.length) continue;
    lines.push('', `## ${g.title} (${list.length})`, '', '| Method | Path | Summary |', '| --- | --- | --- |');
    for (const r of list) {
      lines.push(`| \`${r.method}\` | \`${r.path}\` | ${r.summary || '—'}${r.deprecated ? ' *(deprecated)*' : ''} |`);
    }
  }
  if (other.length) {
    lines.push(
      '',
      `## Other (${other.length})`,
      '',
      '> Routes not yet assigned a family. Naming these is a small doc task;',
      '> leaving them here is what keeps the index honest.',
      '',
      '| Method | Path | Summary |',
      '| --- | --- | --- |',
      ...other.map((r) => `| \`${r.method}\` | \`${r.path}\` | ${r.summary || '—'} |`),
    );
  }

  lines.push('', '---', '', `Generated from \`docs/api/openapi.json\` (${rows.length} operations).`, '');
  return lines.join('\n');
}

const content = build();

if (CHECK) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf-8') : '';
  if (current !== content) {
    console.error(
      '[gen-api-index] docs/API_INDEX.md is out of date.\n' +
        'The API changed and the generated index was not regenerated.\n' +
        'Run: node scripts/gen-api-index.mjs',
    );
    process.exit(1);
  }
  console.log('[gen-api-index] ok — docs/API_INDEX.md matches the OpenAPI spec');
} else {
  writeFileSync(OUT, content, 'utf-8');
  const n = (content.match(/^\| `(GET|POST|PUT|PATCH|DELETE|WS)`/gm) || []).length;
  console.log(`[gen-api-index] wrote docs/API_INDEX.md — ${n} operations`);
}
